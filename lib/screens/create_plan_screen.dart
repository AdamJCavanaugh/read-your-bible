import 'package:flutter/material.dart';
import '../models/bible_data.dart';
import '../models/reading_plan.dart';
import '../providers/app_state.dart';

class CreatePlanScreen extends StatefulWidget {
  const CreatePlanScreen({super.key});

  @override
  State<CreatePlanScreen> createState() => _CreatePlanScreenState();
}

class _CreatePlanScreenState extends State<CreatePlanScreen> {
  final _titleController = TextEditingController();
  final _descriptionController = TextEditingController();
  final _durationController = TextEditingController(text: '365');
  final _repeatController = TextEditingController(text: '2');

  int _durationDays = 365; // Default to 365 days
  final Set<String> _selectedBooks = BibleData.allBooks
      .toSet(); // Default to Whole Bible

  bool _isRepeatEnabled = false; // Default to disabled
  int _repeatCount = 2; // Default repeat count

  @override
  void dispose() {
    _titleController.dispose();
    _descriptionController.dispose();
    _durationController.dispose();
    _repeatController.dispose();
    super.dispose();
  }

  void _updateDuration(int days) {
    setState(() {
      _durationDays = days.clamp(1, 9999);
      _durationController.text = '$_durationDays';
    });
  }

  void _updateRepeat(int count) {
    setState(() {
      _repeatCount = count.clamp(1, 999);
      _repeatController.text = '$_repeatCount';
    });
  }

  void _selectGroup(String group) {
    setState(() {
      _selectedBooks.clear();
      if (group == 'whole') {
        _selectedBooks.addAll(BibleData.allBooks);
      } else if (group == 'ot') {
        _selectedBooks.addAll(BibleData.oldTestamentBooks);
      } else if (group == 'nt') {
        _selectedBooks.addAll(BibleData.newTestamentBooks);
      } else if (group == 'alphabetical') {
        _selectedBooks.addAll(BibleData.alphabeticalBooks);
      } else if (group == 'chronological') {
        _selectedBooks.addAll(BibleData.chronologicalBooks);
      }
    });
  }

  bool get _isWholeBibleSelected =>
      _selectedBooks.length == BibleData.allBooks.length;

  bool get _isOldTestamentSelected =>
      _selectedBooks.length == BibleData.oldTestamentBooks.length &&
      _selectedBooks.containsAll(BibleData.oldTestamentBooks);

  bool get _isNewTestamentSelected =>
      _selectedBooks.length == BibleData.newTestamentBooks.length &&
      _selectedBooks.containsAll(BibleData.newTestamentBooks);

  bool get _isAlphabeticalSelected =>
      _selectedBooks.length == BibleData.alphabeticalBooks.length &&
      _selectedBooks.containsAll(BibleData.alphabeticalBooks);

  bool get _isChronologicalSelected =>
      _selectedBooks.length == BibleData.chronologicalBooks.length &&
      _selectedBooks.containsAll(BibleData.chronologicalBooks);

  String get _autoGeneratedTitle {
    if (_selectedBooks.isEmpty) return 'My Reading Plan';
    if (_isAlphabeticalSelected) return 'Alphabetical Bible in $_durationDays Days';
    if (_isChronologicalSelected) return 'Chronological Bible in $_durationDays Days';
    if (_isWholeBibleSelected) return 'Whole Bible in $_durationDays Days';
    if (_isOldTestamentSelected) return 'Old Testament in $_durationDays Days';
    if (_isNewTestamentSelected) return 'New Testament in $_durationDays Days';
    if (_selectedBooks.length <= 2) {
      return '${_selectedBooks.join(' & ')} in $_durationDays Days';
    }
    return '${_selectedBooks.length} Books in $_durationDays Days';
  }

  int get _totalPlanDays =>
      _isRepeatEnabled ? _durationDays * _repeatCount : _durationDays;

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final state = AppStateScope.of(context);

    return Scaffold(
      appBar: AppBar(title: const Text('Create Reading Plan')),
      body: SingleChildScrollView(
        padding: const EdgeInsets.all(20),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            // Header
            Text(
              'CUSTOM PLAN CREATOR',
              style: theme.textTheme.labelMedium?.copyWith(
                letterSpacing: 1.2,
                fontWeight: FontWeight.bold,
                color: theme.colorScheme.primary,
              ),
            ),
            const SizedBox(height: 4),
            Text(
              'Design Your Journey',
              style: theme.textTheme.headlineMedium?.copyWith(
                fontWeight: FontWeight.w800,
                letterSpacing: -0.5,
              ),
            ),
            const SizedBox(height: 20),

            // Plan Title Input Card
            Card(
              child: Padding(
                padding: const EdgeInsets.all(16),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(
                      'Plan Name',
                      style: theme.textTheme.titleMedium?.copyWith(
                        fontWeight: FontWeight.bold,
                      ),
                    ),
                    const SizedBox(height: 12),
                    TextField(
                      controller: _titleController,
                      decoration: InputDecoration(
                        hintText: _autoGeneratedTitle,
                        hintStyle: TextStyle(
                          color: theme.colorScheme.outline.withValues(
                            alpha: 0.6,
                          ),
                        ),
                        border: OutlineInputBorder(
                          borderRadius: BorderRadius.circular(12),
                        ),
                        filled: true,
                        fillColor: theme.colorScheme.surface,
                        prefixIcon: const Icon(Icons.edit_note),
                      ),
                    ),
                    const SizedBox(height: 12),
                    TextField(
                      controller: _descriptionController,
                      decoration: InputDecoration(
                        hintText: 'Optional description or motivation...',
                        border: OutlineInputBorder(
                          borderRadius: BorderRadius.circular(12),
                        ),
                        filled: true,
                        fillColor: theme.colorScheme.surface,
                      ),
                      maxLines: 2,
                    ),
                  ],
                ),
              ),
            ),

            const SizedBox(height: 20),

            // 1. Duration Selection Card with Custom Number Input
            Card(
              child: Padding(
                padding: const EdgeInsets.all(16),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Row(
                      mainAxisAlignment: MainAxisAlignment.spaceBetween,
                      children: [
                        Text(
                          'Plan Duration',
                          style: theme.textTheme.titleMedium?.copyWith(
                            fontWeight: FontWeight.bold,
                          ),
                        ),

                        // Editable Custom Duration Number Field
                        SizedBox(
                          width: 130,
                          height: 40,
                          child: TextField(
                            controller: _durationController,
                            keyboardType: TextInputType.number,
                            textAlign: TextAlign.center,
                            style: TextStyle(
                              fontWeight: FontWeight.bold,
                              color: theme.colorScheme.onPrimaryContainer,
                            ),
                            decoration: InputDecoration(
                              suffixText: 'Days',
                              contentPadding: const EdgeInsets.symmetric(
                                horizontal: 8,
                                vertical: 8,
                              ),
                              border: OutlineInputBorder(
                                borderRadius: BorderRadius.circular(12),
                              ),
                              filled: true,
                              fillColor: theme.colorScheme.primaryContainer,
                            ),
                            onChanged: (val) {
                              final parsed = int.tryParse(val.trim());
                              if (parsed != null && parsed > 0) {
                                setState(() {
                                  _durationDays = parsed;
                                });
                              }
                            },
                          ),
                        ),
                      ],
                    ),
                    const SizedBox(height: 12),

                    Slider(
                      value: _durationDays.toDouble().clamp(1.0, 366.0),
                      min: 1,
                      max: 366,
                      divisions: 365,
                      label: '$_durationDays Days',
                      onChanged: (val) {
                        _updateDuration(val.toInt());
                      },
                    ),

                    // Quick Snap Duration Shortcuts
                    Text(
                      'Quick Duration Shortcuts:',
                      style: theme.textTheme.labelMedium?.copyWith(
                        color: theme.colorScheme.onSurfaceVariant,
                      ),
                    ),
                    const SizedBox(height: 8),
                    Wrap(
                      spacing: 8,
                      runSpacing: 8,
                      children: [30, 90, 180, 365].map((days) {
                        final isSelected = _durationDays == days;
                        return ChoiceChip(
                          label: Text('$days Days'),
                          selected: isSelected,
                          onSelected: (selected) {
                            if (selected) {
                              _updateDuration(days);
                            }
                          },
                        );
                      }).toList(),
                    ),
                  ],
                ),
              ),
            ),

            const SizedBox(height: 20),

            // 2. Book Selection Card
            Card(
              child: Padding(
                padding: const EdgeInsets.all(16),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Row(
                      mainAxisAlignment: MainAxisAlignment.spaceBetween,
                      children: [
                        Text(
                          'Select Scriptures',
                          style: theme.textTheme.titleMedium?.copyWith(
                            fontWeight: FontWeight.bold,
                          ),
                        ),
                        Text(
                          '${_selectedBooks.length} / 66 Books',
                          style: TextStyle(
                            fontSize: 12,
                            fontWeight: FontWeight.bold,
                            color: theme.colorScheme.primary,
                          ),
                        ),
                      ],
                    ),
                    const SizedBox(height: 12),

                    // Group Selection Shortcuts
                    Text(
                      'Group Selection Shortcuts:',
                      style: theme.textTheme.labelMedium?.copyWith(
                        color: theme.colorScheme.onSurfaceVariant,
                      ),
                    ),
                    const SizedBox(height: 8),
                    Wrap(
                      spacing: 8,
                      runSpacing: 8,
                      children: [
                        ActionChip(
                          avatar: _isAlphabeticalSelected
                              ? const Icon(Icons.check, size: 16)
                              : null,
                          label: const Text('Alphabetical (66)'),
                          backgroundColor: _isAlphabeticalSelected
                              ? theme.colorScheme.primaryContainer
                              : null,
                          onPressed: () => _selectGroup('alphabetical'),
                        ),
                        ActionChip(
                          avatar: _isChronologicalSelected
                              ? const Icon(Icons.check, size: 16)
                              : null,
                          label: const Text('Chronological (66)'),
                          backgroundColor: _isChronologicalSelected
                              ? theme.colorScheme.primaryContainer
                              : null,
                          onPressed: () => _selectGroup('chronological'),
                        ),
                        ActionChip(
                          avatar: _isWholeBibleSelected
                              ? const Icon(Icons.check, size: 16)
                              : null,
                          label: const Text('Whole Bible (66)'),
                          backgroundColor: _isWholeBibleSelected
                              ? theme.colorScheme.primaryContainer
                              : null,
                          onPressed: () => _selectGroup('whole'),
                        ),
                        ActionChip(
                          avatar: _isOldTestamentSelected
                              ? const Icon(Icons.check, size: 16)
                              : null,
                          label: const Text('Old Testament (39)'),
                          backgroundColor: _isOldTestamentSelected
                              ? theme.colorScheme.primaryContainer
                              : null,
                          onPressed: () => _selectGroup('ot'),
                        ),
                        ActionChip(
                          avatar: _isNewTestamentSelected
                              ? const Icon(Icons.check, size: 16)
                              : null,
                          label: const Text('New Testament (27)'),
                          backgroundColor: _isNewTestamentSelected
                              ? theme.colorScheme.primaryContainer
                              : null,
                          onPressed: () => _selectGroup('nt'),
                        ),
                        if (_selectedBooks.isNotEmpty)
                          ActionChip(
                            avatar: const Icon(Icons.clear, size: 16),
                            label: const Text('Clear All'),
                            onPressed: () {
                              setState(() {
                                _selectedBooks.clear();
                              });
                            },
                          ),
                      ],
                    ),

                    const Divider(height: 24),

                    // Individual Books Expansion Tiles
                    Theme(
                      data: theme.copyWith(dividerColor: Colors.transparent),
                      child: Column(
                        children: [
                          ExpansionTile(
                            title: Text(
                              'Old Testament (${_selectedBooks.where((b) => BibleData.oldTestamentBooks.contains(b)).length} / 39)',
                              style: const TextStyle(
                                fontWeight: FontWeight.bold,
                              ),
                            ),
                            children: [
                              Wrap(
                                spacing: 6,
                                runSpacing: 6,
                                children: BibleData.oldTestamentBooks.map((
                                  book,
                                ) {
                                  final isSelected = _selectedBooks.contains(
                                    book,
                                  );
                                  return FilterChip(
                                    label: Text(
                                      book,
                                      style: const TextStyle(fontSize: 12),
                                    ),
                                    selected: isSelected,
                                    onSelected: (selected) {
                                      setState(() {
                                        if (selected) {
                                          _selectedBooks.add(book);
                                        } else {
                                          _selectedBooks.remove(book);
                                        }
                                      });
                                    },
                                  );
                                }).toList(),
                              ),
                            ],
                          ),
                          ExpansionTile(
                            title: Text(
                              'New Testament (${_selectedBooks.where((b) => BibleData.newTestamentBooks.contains(b)).length} / 27)',
                              style: const TextStyle(
                                fontWeight: FontWeight.bold,
                              ),
                            ),
                            children: [
                              Wrap(
                                spacing: 6,
                                runSpacing: 6,
                                children: BibleData.newTestamentBooks.map((
                                  book,
                                ) {
                                  final isSelected = _selectedBooks.contains(
                                    book,
                                  );
                                  return FilterChip(
                                    label: Text(
                                      book,
                                      style: const TextStyle(fontSize: 12),
                                    ),
                                    selected: isSelected,
                                    onSelected: (selected) {
                                      setState(() {
                                        if (selected) {
                                          _selectedBooks.add(book);
                                        } else {
                                          _selectedBooks.remove(book);
                                        }
                                      });
                                    },
                                  );
                                }).toList(),
                              ),
                            ],
                          ),
                        ],
                      ),
                    ),
                  ],
                ),
              ),
            ),

            const SizedBox(height: 20),

            // 3. Repeat Dropdown & Custom Number Entry Card
            Card(
              child: Padding(
                padding: const EdgeInsets.all(16),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    SwitchListTile(
                      contentPadding: EdgeInsets.zero,
                      title: const Text(
                        'Repeat Reading Plan',
                        style: TextStyle(fontWeight: FontWeight.bold),
                      ),
                      subtitle: const Text(
                        'Loop the reading portion multiple times',
                      ),
                      value: _isRepeatEnabled,
                      onChanged: (val) {
                        setState(() {
                          _isRepeatEnabled = val;
                          if (val && _repeatCount < 1) {
                            _updateRepeat(2);
                          }
                        });
                      },
                    ),
                    if (_isRepeatEnabled) ...[
                      const SizedBox(height: 8),
                      Row(
                        mainAxisAlignment: MainAxisAlignment.spaceBetween,
                        children: [
                          const Text(
                            'Number of Repeats:',
                            style: TextStyle(fontWeight: FontWeight.w600),
                          ),

                          // Editable Custom Repeat Number Field
                          SizedBox(
                            width: 130,
                            height: 40,
                            child: TextField(
                              controller: _repeatController,
                              keyboardType: TextInputType.number,
                              textAlign: TextAlign.center,
                              style: TextStyle(
                                fontWeight: FontWeight.bold,
                                color: theme.colorScheme.onSecondaryContainer,
                              ),
                              decoration: InputDecoration(
                                suffixText: 'Times',
                                contentPadding: const EdgeInsets.symmetric(
                                  horizontal: 8,
                                  vertical: 8,
                                ),
                                border: OutlineInputBorder(
                                  borderRadius: BorderRadius.circular(12),
                                ),
                                filled: true,
                                fillColor: theme.colorScheme.secondaryContainer,
                              ),
                              onChanged: (val) {
                                final parsed = int.tryParse(val.trim());
                                if (parsed != null && parsed > 0) {
                                  setState(() {
                                    _repeatCount = parsed;
                                  });
                                }
                              },
                            ),
                          ),
                        ],
                      ),
                    ],
                    const Divider(height: 20),
                    Container(
                      padding: const EdgeInsets.all(12),
                      decoration: BoxDecoration(
                        color: theme.colorScheme.secondaryContainer.withValues(
                          alpha: 0.5,
                        ),
                        borderRadius: BorderRadius.circular(12),
                      ),
                      child: Row(
                        children: [
                          Icon(
                            Icons.event_repeat,
                            color: theme.colorScheme.onSecondaryContainer,
                          ),
                          const SizedBox(width: 12),
                          Expanded(
                            child: Text(
                              _isRepeatEnabled
                                  ? 'Total Duration: $_durationDays days × $_repeatCount repeats = $_totalPlanDays total days.'
                                  : 'Total Duration: $_durationDays days.',
                              style: TextStyle(
                                fontSize: 13,
                                fontWeight: FontWeight.bold,
                                color: theme.colorScheme.onSecondaryContainer,
                              ),
                            ),
                          ),
                        ],
                      ),
                    ),
                  ],
                ),
              ),
            ),

            const SizedBox(height: 24),

            // Submit / Save Buttons
            SizedBox(
              width: double.infinity,
              height: 52,
              child: FilledButton.icon(
                onPressed: _selectedBooks.isEmpty
                    ? null
                    : () {
                        final title = _titleController.text.trim().isEmpty
                            ? _autoGeneratedTitle
                            : _titleController.text.trim();

                        final customPlan = createCustomReadingPlan(
                          title: title,
                          durationDays: _durationDays,
                          selectedBooks: _selectedBooks.toList(),
                          repeatCount: _isRepeatEnabled ? _repeatCount : 1,
                          description: _descriptionController.text,
                          startDate: DateTime.now(), // Plan starts today
                        );

                        state.addCustomPlan(customPlan, setAsActive: true);

                        Navigator.pop(context);

                        ScaffoldMessenger.of(context).showSnackBar(
                          SnackBar(
                            content: Text(
                              '🎉 Custom Plan "$title" created and set as active!',
                            ),
                            behavior: SnackBarBehavior.floating,
                            duration: const Duration(seconds: 3),
                          ),
                        );
                      },
                icon: const Icon(Icons.add_task),
                label: const Text(
                  'Create & Start Plan',
                  style: TextStyle(fontSize: 16, fontWeight: FontWeight.bold),
                ),
              ),
            ),
            const SizedBox(height: 30),
          ],
        ),
      ),
    );
  }
}
